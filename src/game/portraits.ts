/* Her corrupted look: same frame, some cells eaten by noise */
function glitch(art: string[]): string[] {
  return art.map((line, y) =>
    [...line].map((ch, x) => (ch !== " " && (x * 7 + y * 13) % 19 === 0 ? (x % 2 ? "▓" : "▒") : ch)).join(""),
  );
}

